const rtlLanguages = ['ur'];

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  localStorage.setItem('defence_path_lang', lang);
  document.cookie = `defence_path_lang=${lang};path=/;max-age=31536000`;

  // Set RTL or LTR
  if (rtlLanguages.includes(lang)) {
    document.documentElement.setAttribute('dir', 'rtl');
    document.body.classList.add('rtl-layout');
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
    document.body.classList.remove('rtl-layout');
  }

  // Update dropdown value if exists
  const langSelect = document.getElementById('global-lang-select');
  if (langSelect) langSelect.value = lang;

  // Translate all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    } else if (translations['en'][key]) {
      el.textContent = translations['en'][key];
    }
  });

  // Also translate placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('defence_path_lang') || 'en';
  setLanguage(savedLang);

  const langSelect = document.getElementById('global-lang-select');
  if (langSelect) {
    langSelect.addEventListener('change', (e) => {
      setLanguage(e.target.value);
    });
  }
});
